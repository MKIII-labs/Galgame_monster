# -*- coding: utf-8 -*-
"""从 VS Code 的 Seti 图标主题 JSON 生成前端查找表。

    python scripts/gen_seti_icons.py

输入：web/vendor/seti/vs-seti-icon-theme.json（来自 microsoft/vscode，MIT）
输出：web/vendor/seti/seti-map.js（window.GM_SETI）
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "web", "vendor", "seti", "vs-seti-icon-theme.json")
OUT = os.path.join(ROOT, "web", "vendor", "seti", "seti-map.js")


def _char(raw):
    s = str(raw or "").strip()
    # VS Code 的 JSON 里是 "\\E01E"；json 解码后变成字面量 \E01E。
    # 十六进制部分是 E01E，只去掉前导反斜杠，不能连 E 一起吃掉。
    if s.startswith("\\"):
        s = s[1:]
    if s.lower().startswith("u+"):
        s = s[2:]
    try:
        return chr(int(s, 16))
    except ValueError:
        return ""


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        data = json.load(f)
    defs = {}
    for name, d in (data.get("iconDefinitions") or {}).items():
        if not isinstance(d, dict):
            continue
        ch = _char(d.get("fontCharacter"))
        if not ch:
            continue
        defs[name] = [ch, str(d.get("fontColor") or "")]
    light = data.get("light") if isinstance(data.get("light"), dict) else {}
    out = {
        "defs": defs,
        "dark": {
            "file": data.get("file") or "_default",
            "fileExtensions": data.get("fileExtensions") or {},
            "fileNames": data.get("fileNames") or {},
            "folderNames": data.get("folderNames") or {},
            "languageIds": data.get("languageIds") or {},
        },
        "light": {
            "file": light.get("file") or data.get("file") or "_default",
            "fileExtensions": light.get("fileExtensions") or data.get("fileExtensions") or {},
            "fileNames": light.get("fileNames") or data.get("fileNames") or {},
            "folderNames": light.get("folderNames") or data.get("folderNames") or {},
            "languageIds": light.get("languageIds") or data.get("languageIds") or {},
        },
    }
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    text = ("/* Generated by scripts/gen_seti_icons.py from microsoft/vscode "
            "extensions/theme-seti (MIT). Do not edit manually. */\n"
            "window.GM_SETI = " + body + ";\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d defs, %d ext, %d names)"
          % (OUT, len(defs), len(out["dark"]["fileExtensions"]),
             len(out["dark"]["fileNames"])))


if __name__ == "__main__":
    main()

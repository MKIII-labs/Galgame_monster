# -*- coding: utf-8 -*-
"""读写 Windows 快捷方式（.lnk）与它的 System.AppUserModel.ID。

为什么需要这个模块
------------------
Electron 的 BrowserWindow `icon` 只设置窗口的 WM_SETICON；Windows 10/11 的任务栏
按钮图标是按 **AppUserModelID** 找「带同一个 System.AppUserModel.ID 的快捷方式」，
再用那条快捷方式的图标。找不到就回落到进程 exe（electron.exe）自带的原子图标 ——
这就是只设 `icon:` 没效果的原因。

实测（2026-10-25，本机）：
  * 只设 icon                         → 任务栏显示 Electron 原子图标
  * icon + 自定义 AUMID，无快捷方式    → 仍然原子图标
  * icon + AUMID + 同 ID 的快捷方式    → 显示 app.ico

还有一点很重要：如果用户曾经「固定到任务栏」，资源管理器会给那条快捷方式写一个
`Microsoft.AutoGenerated.{GUID}` 形式的 AUMID（本机就有一条）。窗口必须沿用这个 ID，
才能并到已固定的按钮上；自己另造一个 ID 只会多出第二个按钮。

WScript.Shell 设不了这个属性，必须走 COM（IShellLinkW + IPropertyStore）。
这里用 ctypes 直接调，不引入 pywin32 / comtypes。
"""
import ctypes
import os
import sys
from ctypes import wintypes

# 全新环境（没有任何已存在的快捷方式）时用的 ID；
# 必须与 desktop/main.js 里的兜底值完全一致。
AUMID = "GalgameMonster.Desktop"

_CLSID_SHELLLINK = "{00021401-0000-0000-C000-000000000046}"
_IID_SHELLLINK_W = "{000214F9-0000-0000-C000-000000000046}"
_IID_PROPERTY_STORE = "{886D8EEB-8CF2-4446-8D02-CDBA1DBDCF99}"
_IID_PERSIST_FILE = "{0000010B-0000-0000-C000-000000000046}"

_FMTID_APP_USER_MODEL = "{9F4C2855-9F79-4B39-A8D0-E1D42DE1D5F3}"   # System.AppUserModel
_PID_APP_USER_MODEL_ID = 5                                          # .ID

_VT_LPWSTR = 31
_CLSCTX_INPROC_SERVER = 1


class _GUID(ctypes.Structure):
    _fields_ = [("Data1", wintypes.DWORD), ("Data2", wintypes.WORD),
                ("Data3", wintypes.WORD), ("Data4", ctypes.c_ubyte * 8)]


class _PROPERTYKEY(ctypes.Structure):
    _fields_ = [("fmtid", _GUID), ("pid", wintypes.DWORD)]


class _PROPVARIANT(ctypes.Structure):
    """只关心 VT_LPWSTR，指针在偏移 8。"""
    _fields_ = [("vt", wintypes.USHORT), ("_r1", wintypes.WORD),
                ("_r2", wintypes.WORD), ("_r3", wintypes.WORD),
                ("p", ctypes.c_void_p), ("_pad", ctypes.c_void_p)]


# ---------------------------------------------------------------- COM 小工具

def _guid(text):
    g = _GUID()
    ctypes.windll.ole32.CLSIDFromString(ctypes.c_wchar_p(text), ctypes.byref(g))
    return g


def _vtable(obj):
    """COM 对象头指针 → 函数表；0/1/2 固定是 QueryInterface/AddRef/Release。"""
    head = ctypes.cast(obj, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    return ctypes.cast(head, ctypes.POINTER(ctypes.c_void_p))


def _fn(obj, index, *arg_types):
    """取函数表第 index 项；所有方法都按 HRESULT 返回处理。"""
    proto = ctypes.WINFUNCTYPE(ctypes.HRESULT, ctypes.c_void_p, *arg_types)
    return proto(_vtable(obj)[index])


def _query(obj, iid):
    proto = ctypes.WINFUNCTYPE(ctypes.HRESULT, ctypes.c_void_p,
                               ctypes.POINTER(_GUID), ctypes.POINTER(ctypes.c_void_p))
    out = ctypes.c_void_p()
    hr = proto(_vtable(obj)[0])(obj, ctypes.byref(iid), ctypes.byref(out))
    if hr != 0:
        raise OSError("QueryInterface 失败：0x%08x" % (hr & 0xFFFFFFFF))
    return out


def _release(obj):
    if not obj:
        return
    try:
        _fn(obj, 2)(obj)                       # Release 无参数
    except Exception:
        pass


def _open(lnk):
    """打开已有 .lnk → (IShellLinkW, IPersistFile)；调用方负责 Release。"""
    ole32 = ctypes.windll.ole32
    ole32.CoInitialize(None)
    link = ctypes.c_void_p()
    hr = ole32.CoCreateInstance(ctypes.byref(_guid(_CLSID_SHELLLINK)), None,
                                _CLSCTX_INPROC_SERVER,
                                ctypes.byref(_guid(_IID_PERSIST_FILE)),
                                ctypes.byref(link))
    if hr != 0:
        raise OSError("创建 ShellLink 失败：0x%08x" % (hr & 0xFFFFFFFF))
    # IPersistFile: 5=Load，6=Save
    try:
        _fn(link, 5, ctypes.c_wchar_p, ctypes.c_int)(link, lnk, 0)
    except Exception:
        _release(link)
        raise
    try:
        shell = _query(link, _guid(_IID_SHELLLINK_W))
    except Exception:
        _release(link)
        raise
    return shell, link


# ---------------------------------------------------------------- 公开接口

def start_menu_lnk():
    base = os.environ.get("APPDATA") or ""
    return os.path.join(base, "Microsoft", "Windows", "Start Menu", "Programs",
                        "Galgame_monster.lnk")


def pinned_lnk():
    """任务栏上已固定的那条（如果用户固定过）。"""
    base = os.environ.get("APPDATA") or ""
    return os.path.join(base, "Microsoft", "Internet Explorer", "Quick Launch",
                        "User Pinned", "TaskBar", "Galgame_monster.lnk")


def read(lnk):
    """读回 {target, args, workdir, icon, aumid}；文件不存在或失败返回 {}。"""
    if not sys.platform.startswith("win") or not os.path.isfile(lnk):
        return {}
    shell = persist = None
    result = {}
    try:
        shell, persist = _open(lnk)
        buf = ctypes.create_unicode_buffer(32768)
        # IShellLinkW: 3=GetPath 8=GetWorkingDirectory 10=GetArguments 16=GetIconLocation
        _fn(shell, 3, ctypes.c_wchar_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_uint)(
            shell, buf, len(buf), None, 0)
        result["target"] = buf.value or ""
        _fn(shell, 8, ctypes.c_wchar_p, ctypes.c_int)(shell, buf, len(buf))
        result["workdir"] = buf.value or ""
        _fn(shell, 10, ctypes.c_wchar_p, ctypes.c_int)(shell, buf, len(buf))
        result["args"] = buf.value or ""
        idx = ctypes.c_int(0)
        _fn(shell, 16, ctypes.c_wchar_p, ctypes.c_int, ctypes.POINTER(ctypes.c_int))(
            shell, buf, len(buf), ctypes.byref(idx))
        result["icon"] = (buf.value or "") + (",%d" % idx.value if idx.value else "")

        store = _query(shell, _guid(_IID_PROPERTY_STORE))
        try:
            key = _PROPERTYKEY()
            key.fmtid = _guid(_FMTID_APP_USER_MODEL)
            key.pid = _PID_APP_USER_MODEL_ID
            pv = _PROPVARIANT()
            # IPropertyStore: 5=GetValue
            _fn(store, 5, ctypes.POINTER(_PROPERTYKEY), ctypes.POINTER(_PROPVARIANT))(
                store, ctypes.byref(key), ctypes.byref(pv))
            if pv.vt == _VT_LPWSTR and pv.p:
                result["aumid"] = ctypes.wstring_at(pv.p) or ""
                ctypes.windll.ole32.PropVariantClear(ctypes.byref(pv))
        finally:
            _release(store)
        return result
    except Exception:
        return {}
    finally:
        _release(shell)
        _release(persist)


def _same_path(a, b):
    try:
        return os.path.normcase(os.path.normpath(a or "")) == \
               os.path.normcase(os.path.normpath(b or ""))
    except Exception:
        return (a or "") == (b or "")


def ensure(lnk, target, args="", icon="", aumid=AUMID, workdir="",
           desc="Galgame_monster"):
    """确保快捷方式存在、内容与期望一致，且带上了 aumid。

    内容已经对就完全不碰文件：重复覆盖 .lnk 会让资源管理器重新解析图标来源，
    容易再退化成通用占位图标。
    返回 (是否已就绪, 说明)。
    """
    if not sys.platform.startswith("win"):
        return False, "非 Windows，跳过"
    if not target or not os.path.isfile(target):
        return False, "目标不存在：%s" % target

    cur = read(lnk)
    if (cur and (cur.get("aumid") or "") == (aumid or "")
            and _same_path(cur.get("target"), target)
            and _same_path(cur.get("workdir"), workdir)
            and _same_path(cur.get("icon").split(",")[0] if cur.get("icon") else "", icon)
            and os.path.normcase(cur.get("args") or "") == os.path.normcase(args or "")):
        return True, "已存在"

    ole32 = ctypes.windll.ole32
    ole32.CoInitialize(None)
    link = ctypes.c_void_p()
    hr = ole32.CoCreateInstance(ctypes.byref(_guid(_CLSID_SHELLLINK)), None,
                                _CLSCTX_INPROC_SERVER,
                                ctypes.byref(_guid(_IID_SHELLLINK_W)),
                                ctypes.byref(link))
    if hr != 0:
        return False, "创建 ShellLink 失败：0x%08x" % (hr & 0xFFFFFFFF)

    store = persist = None
    try:
        os.makedirs(os.path.dirname(lnk), exist_ok=True)
        # IShellLinkW: 7=SetDescription 9=SetWorkingDirectory 11=SetArguments
        #              17=SetIconLocation 20=SetPath
        _fn(link, 20, ctypes.c_wchar_p)(link, target)
        _fn(link, 11, ctypes.c_wchar_p)(link, args or "")
        _fn(link, 9, ctypes.c_wchar_p)(link, workdir or "")
        _fn(link, 7, ctypes.c_wchar_p)(link, desc or "")
        if icon:
            _fn(link, 17, ctypes.c_wchar_p, ctypes.c_int)(link, icon, 0)

        if aumid:
            store = _query(link, _guid(_IID_PROPERTY_STORE))
            key = _PROPERTYKEY()
            key.fmtid = _guid(_FMTID_APP_USER_MODEL)
            key.pid = _PID_APP_USER_MODEL_ID
            pv = _PROPVARIANT()
            pv.vt = _VT_LPWSTR
            text = ctypes.c_wchar_p(aumid)      # 保证在调用期间存活
            pv.p = ctypes.cast(text, ctypes.c_void_p)
            # IPropertyStore: 6=SetValue 7=Commit
            _fn(store, 6, ctypes.POINTER(_PROPERTYKEY), ctypes.POINTER(_PROPVARIANT))(
                store, ctypes.byref(key), ctypes.byref(pv))
            _fn(store, 7)(store)

        persist = _query(link, _guid(_IID_PERSIST_FILE))
        # IPersistFile: 6=Save
        _fn(persist, 6, ctypes.c_wchar_p, ctypes.c_int)(persist, lnk, 1)
        return True, "已创建"
    except Exception as e:
        return False, "写入失败：%s" % e
    finally:
        _release(persist)
        _release(store)
        _release(link)
